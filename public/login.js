const form = document.querySelector('#login-form');
const summary = document.querySelector('#login-errors');
const submit = document.querySelector('#login-submit');
const password = document.querySelector('#password');
const fields = ['email', 'password'];
if (new URLSearchParams(location.search).has('expired')) document.querySelector('#session-notice').hidden = false;
function showError(message, invalidFields = {}) {
  summary.textContent = message; summary.hidden = false;
  for (const [name, text] of Object.entries(invalidFields)) {
    const input = document.getElementById(name);
    input.setAttribute('aria-invalid', 'true');
    const error = document.getElementById(`${name}-error`); error.textContent = text; error.hidden = false;
  }
  summary.focus();
}
document.querySelector('#show-password').addEventListener('click', event => {
  const visible = password.type === 'password'; password.type = visible ? 'text' : 'password';
  event.currentTarget.textContent = visible ? 'Hide' : 'Show'; event.currentTarget.setAttribute('aria-pressed', String(visible));
});
form.addEventListener('submit', async event => {
  event.preventDefault(); summary.hidden = true;
  const errors = {};
  for (const name of fields) {
    const input = document.getElementById(name); input.removeAttribute('aria-invalid'); document.getElementById(`${name}-error`).hidden = true;
    if (!input.validity.valid) errors[name] = name === 'email' ? 'Enter a valid email address.' : 'Enter your password.';
  }
  if (Object.keys(errors).length) { showError('Please check the highlighted fields.', errors); return; }
  submit.disabled = true; submit.textContent = 'Signing you in…'; form.setAttribute('aria-busy', 'true');
  try {
    const response = await fetch('/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(Object.fromEntries(new FormData(form))) });
    const result = await response.json();
    if (!response.ok) { password.value = ''; showError(result.message || 'Sign-in failed. Please try again.'); return; }
    // Only destinations generated by the server for the two known roles.
    if (!['/workspace/manager/overview', '/workspace/worker/shifts'].includes(result.redirectTo)) throw new Error('Unexpected destination');
    form.reset(); location.replace(result.redirectTo);
  } catch { showError('We couldn’t reach the server. Please try again.'); }
  finally { submit.disabled = false; submit.innerHTML = 'Sign in <span aria-hidden="true">↗</span>'; form.removeAttribute('aria-busy'); }
});
